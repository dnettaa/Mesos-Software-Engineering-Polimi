package it.polimi.ingsw.model.game;

/**
 * Represents the era associated with the game cards.
 * Cards are ordered by era in the deck, and the game advances to a new era
 * when a card belonging to that era is revealed.
 *
 * @author Luca Grecchi
 */
public enum Era {
    Era1,
    Era2,
    Era3
}
